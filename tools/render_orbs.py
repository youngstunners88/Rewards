def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    log("Blender %s | out=%s" % (bpy.app.version_string, OUT_DIR))

    if PREVIEW:
        render_preview()
        log("PREVIEW COMPLETE")
        return

    out_webm = os.path.join(OUT_DIR, "orb-unlock.webm")
    out_mp4 = os.path.join(OUT_DIR, "orb-unlock.mp4")

    if not SKIP_VIDEO:
        os.makedirs(TMP_ROOT, exist_ok=True)
        if os.path.isdir(FRAME_DIR):
            shutil.rmtree(FRAME_DIR)
        os.makedirs(FRAME_DIR)

        sc = fresh_scene()
        build_space(sc, with_starfield=True)
        rig = build_orb(sc, spec_dict(HERO_SPEC), for_animation=True)
        build_animation(rig)
        setup_compositor(sc, quality="Medium", threshold=0.80,
                         strength=0.85, size=0.62)
        render_animation_frames(sc, rig, FRAME_DIR)

        if not NO_ENCODE:
            encode(FRAME_DIR, out_webm, out_mp4)
            for path in (out_webm, out_mp4):
                info = ffprobe(path)
                log("VERIFY %s -> %s  (%d bytes)"
                    % (os.path.basename(path), info, os.path.getsize(path)))
        if not KEEP_FRAMES:
            shutil.rmtree(FRAME_DIR, ignore_errors=True)
            log("Temporary frames deleted.")

    if not SKIP_STILLS:
        render_icons()
        render_poster()

    log("DONE. Files in %s:" % OUT_DIR)
    for f in sorted(os.listdir(OUT_DIR)):
        log("  %-32s %8d bytes" % (f, os.path.getsize(os.path.join(OUT_DIR, f))))


if __name__ == "__main__":
    main()
