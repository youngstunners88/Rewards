def kf_scale(obj, pairs):
    for f, v in pairs:
        obj.scale = (v, v, v)
        obj.keyframe_insert(data_path="scale", frame=f)


def kf_strength(mat, pairs):
    em = emission_node(mat)
    for f, v in pairs:
        em.inputs["Strength"].default_value = v
        em.inputs["Strength"].keyframe_insert(data_path="default_value", frame=f)


def kf_spin(obj, base, rate, step=7):
    """Near-linear spin via many evenly spaced keys (Bezier ~= linear)."""
    for f in list(range(1, N_FRAMES + 1, step)) + [N_FRAMES]:
        t = (f - 1) / float(FPS)
        obj.rotation_euler = tuple(base[i] + rate[i] * t for i in range(3))
        obj.keyframe_insert(data_path="rotation_euler", frame=f)


def try_linear(obj):
    """Best-effort LINEAR interpolation, works with slotted (5.x) actions."""
    ad = obj.animation_data
    if not ad or not ad.action:
        return
    act = ad.action
    fcs = []
    try:
        fcs = list(act.fcurves)
    except Exception:
        fcs = []
    if not fcs:
        try:
            for layer in act.layers:
                for strip in layer.strips:
                    for bag in strip.channelbags:
                        fcs.extend(list(bag.fcurves))
        except Exception:
            pass
    for fc in fcs:
        for kp in fc.keyframe_points:
            kp.interpolation = "LINEAR"


ENVELOPE = [
    (1, 0.10), (18, 0.16), (28, 0.28), (40, 0.55), (52, 1.28),
    (62, 1.06), (72, 1.00), (96, 1.06), (120, 1.10), (132, 1.32),
    (146, 1.16), (152, 0.85), (160, 1.30), (168, 0.58),
]


def build_animation(rig):
    """Keyframe the whole 7-second storyboard."""
    sp = rig["spec"]
    root = rig["root"]

    # Phase B: orb scales up from zero with a small overshoot.
    kf_scale(root, [(1, 0.001), (24, 0.001), (30, 0.03), (44, 0.55),
                    (56, 0.98), (64, 1.12), (74, 1.00), (168, 1.00)])

    # Rings assemble with a stagger, then spin in alternating directions.
    for i, pv in enumerate(rig["ring_pivots"]):
        tilt = sp["tilts"][i % len(sp["tilts"])]
        kf_scale(pv, [(1, 0.001), (30 + i * 5, 0.001),
                      (48 + i * 7, 1.14), (64 + i * 7, 1.00),
                      (168, 1.00)])
        rate = (0.90 + 0.22 * i) * (1.0 if i % 2 == 0 else -1.0)
        kf_spin(pv, (tilt[0], tilt[1], tilt[2]), (0.0, 0.0, rate))
        try_linear(pv)

    # Sigil ring counter-rotates.
    kf_spin(rig["rune_pivot"], (0.16, 0.0, 0.0), (0.0, 0.0, -0.55))
    try_linear(rig["rune_pivot"])

    # Inner core tumbles slowly.
    kf_spin(rig["core"], (0.0, 0.0, 0.0), (0.34, 0.46, 0.18))
    try_linear(rig["core"])

    # Spark shells orbit opposite ways, then burst outward (phase D).
    for k, sh in enumerate(rig["spark_shells"]):
        kf_scale(sh, [(1, 0.001), (34 + k * 6, 0.001), (54 + k * 5, 1.0),
                      (120, 1.0), (130, 1.55), (145, 2.45),
                      (156, 1.35), (168, 1.15)])
        sign = 1.0 if k == 0 else -1.0
        kf_spin(sh, (0.25 * k, 0.4 * k, 0.0),
                (0.22 * sign, 0.30 * sign, 0.85 * sign))
        try_linear(sh)

    # Animated 4-D noise W => swirling energy inside the core.
    noise = rig["core_noise"]
    for f in list(range(1, N_FRAMES + 1, 14)) + [N_FRAMES]:
        noise.inputs["W"].default_value = 6.4 * (f - 1) / float(FPS)
        noise.inputs["W"].keyframe_insert(data_path="default_value", frame=f)

    # Global brightness envelope: dark start, flash, glow pulse, dark-ish end.
    for mat, base in rig["tintables"]:
        kf_strength(mat, [(f, base * mul) for f, mul in ENVELOPE])

    # Gathering motes: converge inward, then disappear.
    kf_scale(rig["gather"], [(1, 3.2), (20, 2.4), (40, 1.15), (52, 0.35),
                             (58, 0.001), (168, 0.001)])
    kf_strength(rig["gather_mat"],
                [(1, 0.55), (20, 1.25), (38, 2.10), (50, 0.65),
                 (56, 0.0), (168, 0.0)])

    # Ignition flash.
    kf_scale(rig["flash"], [(1, 0.001), (46, 0.001), (52, 0.22),
                            (56, 0.45), (62, 0.22), (70, 0.001),
                            (168, 0.001)])
    kf_strength(rig["flash_mat"],
                [(1, 0.0), (46, 0.0), (52, 5.5), (56, 8.0),
                 (62, 4.5), (70, 0.0), (168, 0.0)])

    # Shockwave ring expands out of frame and fades.
    kf_scale(rig["shock"], [(1, 0.001), (124, 0.001), (126, 0.55),
                            (136, 2.60), (152, 5.60), (154, 0.001),
                            (168, 0.001)])
    kf_strength(rig["shock_mat"],
                [(1, 0.0), (124, 0.0), (128, 3.2), (136, 1.9),
                 (150, 0.25), (154, 0.0), (168, 0.0)])


