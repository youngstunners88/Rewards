def fresh_scene():
    """Fully reset Blender to an empty, deterministic, cheap Cycles scene."""
    bpy.ops.wm.read_factory_settings(use_empty=True)
    sc = bpy.context.scene
    sc.render.engine = "CYCLES"
    sc.cycles.device = "CPU"
    sc.cycles.samples = ANIM_SAMPLES
    sc.cycles.use_denoising = False
    try:
        sc.cycles.use_adaptive_sampling = False
    except Exception:
        pass
    sc.render.use_persistent_data = True
    sc.render.use_compositing = True
    sc.render.resolution_percentage = 100
    sc.render.image_settings.file_format = "PNG"
    sc.render.image_settings.color_depth = "8"
    sc.render.image_settings.compression = 15
    sc.render.fps = FPS
    sc.render.fps_base = 1.0
    sc.frame_start = 1
    sc.frame_end = N_FRAMES
    sc.frame_set(1)

    sc.view_settings.view_transform = os.environ.get(
        "ORB_VIEW_TRANSFORM", "Standard")
    sc.view_settings.look = "None"
    sc.view_settings.exposure = 0.0
    sc.view_settings.gamma = 1.0

    # near-black world (the backdrop plane supplies the visible gradient)
    w = bpy.data.worlds.new("Void")
    sc.world = w
    w.use_nodes = True
    bg = w.node_tree.nodes.get("Background")
    bg.inputs["Color"].default_value = (0.0012, 0.0008, 0.0030, 1)
    bg.inputs["Strength"].default_value = 1.0

    cd = bpy.data.cameras.new("OrbCamera")
    cd.lens = 58
    cam = bpy.data.objects.new("OrbCamera", cd)
    sc.collection.objects.link(cam)
    cam.location = (0.0, 0.0, 9.0)
    cam.rotation_euler = (0.0, 0.0, 0.0)
    sc.camera = cam
    return sc


def setup_compositor(sc, quality="High", threshold=0.80, strength=0.85,
                     size=0.62):
    """Blender 5.0+ compositor: a genuine Fog Glow bloom (never skipped)."""
    ng = bpy.data.node_groups.new("OrbBloom", "CompositorNodeTree")
    sc.compositing_node_group = ng
    ng.interface.new_socket("Image", in_out="OUTPUT",
                            socket_type="NodeSocketColor")
    rl = ng.nodes.new("CompositorNodeRLayers")
    gl = ng.nodes.new("CompositorNodeGlare")
    out = ng.nodes.new("NodeGroupOutput")
    gl.inputs["Type"].default_value = "Fog Glow"     # enum *string*, not FOG_GLOW
    gl.inputs["Quality"].default_value = quality
    gl.inputs["Threshold"].default_value = threshold
    gl.inputs["Strength"].default_value = strength
    gl.inputs["Size"].default_value = size
    gl.inputs["Saturation"].default_value = 1.0
    ng.links.new(rl.outputs["Image"], gl.inputs["Image"])
    ng.links.new(gl.outputs["Image"], out.inputs[0])
    sc.render.use_compositing = True
    return ng


def empty(scene, name, parent=None):
    ob = bpy.data.objects.new(name, None)
    scene.collection.objects.link(ob)
    ob.empty_display_type = "PLAIN_AXES"
    ob.empty_display_size = 0.25
    if parent is not None:
        ob.parent = parent
    return ob


def build_space(scene, with_starfield):
    """Dark nebula plane + two sparse emissive star layers (video/poster only)."""
    if not with_starfield:
        return []
    plane = mesh_from_pydata(
        scene, "NebulaPlane",
        [(-22, -22, -12), (22, -22, -12), (22, 22, -12), (-22, 22, -12)],
        [(0, 1, 2, 3)])
    plane.data.materials.append(make_backdrop_material())

    dim = stars_mesh(scene, "StarsDim", 150, 11, 8.0, -11.0, -9.5, 0.030, 0.065)
    dim.data.materials.append(
        make_emission("StarDim", (0.55, 0.62, 0.95), 1.1))
    bright = stars_mesh(scene, "StarsBright", 26, 29, 7.5, -10.8, -9.6,
                        0.055, 0.105)
    bright.data.materials.append(
        make_emission("StarBright", clight((0.60, 0.75, 1.0), 0.35), 3.4))
    return [plane, dim, bright]


def build_orb(scene, sp, for_animation):
    """Construct one complete orb rig. Returns handles for posing/keyframing."""
    p = hex_linear(sp["primary"])
    s = hex_linear(sp["secondary"])
    accent_mix = sp["accent"]
    accent = cmix(p, s, accent_mix)
    rng = random.Random(sum(ord(c) for c in sp["slug"]))

    root = empty(scene, "OrbRoot")

    # -- ghost shell ---------------------------------------------------------
    shell = make_body(scene, "Shell", "smooth", 1.0)
    shell.parent = root
    shell_mat = make_shell_material("ShellMat", p, s, sp["ramp"], 0.90)
    shell.data.materials.append(shell_mat)

    # -- inner core ----------------------------------------------------------
    core = make_body(scene, "Core", sp["core"], sp["inner"])
    core.parent = root
    core_mat, core_noise = make_core_material(
        "CoreMat", p, s, accent_mix, 1.90)
    core.data.materials.append(core_mat)

    tintables = [(shell_mat, 0.90), (core_mat, 1.90)]

    # -- rings ---------------------------------------------------------------
    ring_pivots, ring_meshes = [], []
    for i in range(sp["rings"]):
        tilt = sp["tilts"][i % len(sp["tilts"])]
        pv = empty(scene, "RingPivot_%d" % i, root)
        pv.rotation_euler = (tilt[0], tilt[1], tilt[2])
        ring_pivots.append(pv)
        r_major = sp["ring_r"] + i * 0.16
        r_minor = 0.026 + (i % 3) * 0.014
        rm = torus_mesh(scene, "Ring_%d" % i, r_major, r_minor, 72, 8)
        rm.parent = pv
        col = clight(p if i % 2 == 0 else accent, 0.08 + 0.05 * i)
        stg = 1.65
        rmat = make_emission("RingMat_%d" % i, col, stg)
        rm.data.materials.append(rmat)
        ring_meshes.append(rm)
        tintables.append((rmat, stg))

    # -- rune / sigil ring (flat, camera-facing) -----------------------------
    rune_pivot = empty(scene, "RunePivot", root)
    rune_pivot.rotation_euler = (0.16, 0.0, 0.0)
    rune_mat = make_emission("RuneMat", clight(accent, 0.22), 2.4)
    tintables.append((rune_mat, 2.4))
    rune_meshes = []
    n_runes = sp["runes"]
    for i in range(n_runes):
        a = 2.0 * math.pi * i / max(1, n_runes)
        rr = sp["ring_r"] + 0.26
        d = octa_mesh(scene, "Rune_%d" % i, 0.075)
        d.location = (rr * math.cos(a), rr * math.sin(a), 0.0)
        d.rotation_euler = (0.0, 0.0, a + math.pi / 4.0)
        d.parent = rune_pivot
        d.data.materials.append(rune_mat)
        rune_meshes.append(d)

    # -- orbiting spark shells (two, counter-rotating) -----------------------
    spark_shells, spark_mats = [], []
    for k in range(2):
        sh = empty(scene, "SparkShell_%d" % k, root)
        sh.rotation_euler = (0.25 * k, 0.4 * k, 0.0)
        spark_shells.append(sh)
        n = sp["sparks"] // 2
        stg = 3.4
        smat = make_emission("SparkMat_%d" % k,
                             clight(p if k == 0 else accent, 0.32), stg)
        tintables.append((smat, stg))
        spark_mats.append(smat)
        for i in range(n):
            # uniform-ish points on a spherical shell
            u = rng.uniform(-1.0, 1.0)
            a = rng.uniform(0.0, 2.0 * math.pi)
            rad = (1.85 + 0.55 * rng.random()) + 0.12 * k
            q = math.sqrt(max(0.0, 1.0 - u * u))
            d = octa_mesh(scene, "Spark_%d_%d" % (k, i),
                          rng.uniform(0.020, 0.048))
            d.location = (rad * q * math.cos(a), rad * q * math.sin(a),
                          rad * u)
            d.parent = sh
            d.data.materials.append(smat)

    rig = dict(root=root, shell=shell, core=core, core_noise=core_noise,
               ring_pivots=ring_pivots, ring_meshes=ring_meshes,
               rune_pivot=rune_pivot, rune_meshes=rune_meshes,
               spark_shells=spark_shells, tintables=tintables,
               spec=sp)

    if for_animation:
        build_fx(scene, p, s, accent, rig)
    return rig


def build_fx(scene, p, s, accent, rig):
    """Extra objects used only by the 7-second reveal animation."""
    # Gathering motes (phase A) -- converge toward the centre, then vanish.
    gather = empty(scene, "GatherField")
    g_mat = make_emission("GatherMat", clight(accent, 0.25), 1.0)
    rng = random.Random(77)
    for i in range(30):
        u = rng.uniform(-1.0, 1.0)
        a = rng.uniform(0.0, 2.0 * math.pi)
        rad = rng.uniform(0.9, 1.5)
        q = math.sqrt(max(0.0, 1.0 - u * u))
        d = octa_mesh(scene, "Mote_%d" % i, rng.uniform(0.020, 0.042))
        d.location = (rad * q * math.cos(a), rad * q * math.sin(a), rad * u)
        d.parent = gather
        d.data.materials.append(g_mat)

    # Bright ignition flash.
    flash = make_body(scene, "Flash", "smooth", 1.0)
    f_mat = make_emission("FlashMat", clight(p, 0.55), 0.0)
    flash.data.materials.append(f_mat)

    # Expanding shockwave ring.
    shock = torus_mesh(scene, "Shockwave", 1.0, 0.040, 96, 8)
    s_mat = make_emission("ShockMat", clight(accent, 0.18), 0.0)
    shock.data.materials.append(s_mat)

    rig.update(gather=gather, gather_mat=g_mat, flash=flash, flash_mat=f_mat,
               shock=shock, shock_mat=s_mat)


