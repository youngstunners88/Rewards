def pose_still(rig, index=0):
    """A fixed, attractive, centred pose for a collectible icon."""
    sp = rig["spec"]
    root = rig["root"]
    root.scale = (1.0, 1.0, 1.0)
    root.rotation_euler = (0.0, 0.0, 0.0)

    for i, pv in enumerate(rig["ring_pivots"]):
        tilt = sp["tilts"][i % len(sp["tilts"])]
        pv.rotation_euler = (tilt[0], tilt[1], tilt[2] + 0.35 * i + 0.2)
        pv.scale = (1.0, 1.0, 1.0)
    rig["rune_pivot"].rotation_euler = (0.16, 0.0, 0.22 + 0.15 * index)
    for k, sh in enumerate(rig["spark_shells"]):
        sh.rotation_euler = (0.25 * k + 0.12, 0.4 * k - 0.10,
                             0.30 * (1 if k == 0 else -1))
        sh.scale = (1.0, 1.0, 1.0)
    rig["core"].rotation_euler = (0.25, 0.35, 0.18)


