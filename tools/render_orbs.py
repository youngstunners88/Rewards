def emission_node(mat):
    for n in mat.node_tree.nodes:
        if n.type == "EMISSION":
            return n
    return None


def make_emission(name, color, strength):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Color"].default_value = crgba(color)
    em.inputs["Strength"].default_value = strength
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    nt.links.new(em.outputs[0], out.inputs["Surface"])
    m.diffuse_color = crgba(color)
    return m


def ramp_set(ramp, stops):
    """stops = [(pos, (r,g,b)), ...]; rebuilds the ColorRamp elements."""
    els = ramp.color_ramp.elements
    while len(els) > 1:
        els.remove(els[1])
    els[0].position = stops[0][0]
    els[0].color = crgba(stops[0][1])
    for pos, col in stops[1:]:
        e = els.new(pos)
        e.color = crgba(col)


def make_shell_material(name, p, s, mode, strength):
    """
    Ghostly glass shell: the centre is transparent (so the inner core shows
    through) and the grazing rim is a bright emissive halo. Fresnel drives
    BOTH the transparency mix and the rim colour ramp.
    """
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()

    out = nt.nodes.new("ShaderNodeOutputMaterial")
    mix = nt.nodes.new("ShaderNodeMixShader")
    trans = nt.nodes.new("ShaderNodeBsdfTransparent")
    trans.inputs["Color"].default_value = (1, 1, 1, 1)
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Strength"].default_value = strength

    lw = nt.nodes.new("ShaderNodeLayerWeight")
    lw.inputs["Blend"].default_value = 0.30
    power = nt.nodes.new("ShaderNodeMath")
    power.operation = "POWER"
    # A high exponent keeps the bright halo as a crisp coloured rim. The
    # sphere is seen from both sides through the transparent centre, so the
    # rim contribution is effectively doubled -- keep it dim and saturated.
    power.inputs[1].default_value = 4.5
    bias = nt.nodes.new("ShaderNodeMath")
    bias.operation = "ADD"
    bias.inputs[1].default_value = 0.10   # faint body glow, core still visible

    ramp = nt.nodes.new("ShaderNodeValToRGB")
    if mode == "eclipse":
        # black core, incandescent coloured rim
        ramp_set(ramp, [(0.0, cdark(s, 0.6)),
                        (0.45, cmix(s, p, 0.50)),
                        (0.78, clight(p, 0.06)),
                        (1.0, clight(p, 0.18))])
    elif mode == "prism":
        ramp_set(ramp, [(0.0, cmix(p, s, 0.45)),
                        (0.40, clight(cmix(p, s, 0.65), 0.04)),
                        (0.72, clight(p, 0.08)),
                        (1.0, clight(p, 0.20))])
    else:  # radiant
        ramp_set(ramp, [(0.0, cmix(s, p, 0.55)),
                        (0.45, clight(p, 0.02)),
                        (0.78, clight(p, 0.06)),
                        (1.0, clight(p, 0.14))])

    nt.links.new(lw.outputs["Fresnel"], power.inputs[0])
    nt.links.new(power.outputs[0], bias.inputs[0])
    nt.links.new(bias.outputs[0], mix.inputs[0])         # Fac
    nt.links.new(trans.outputs[0], mix.inputs[1])        # centre
    nt.links.new(lw.outputs["Fresnel"], ramp.inputs["Fac"])
    nt.links.new(ramp.outputs["Color"], em.inputs["Color"])
    nt.links.new(em.outputs[0], mix.inputs[2])           # rim
    nt.links.new(mix.outputs[0], out.inputs["Surface"])
    m.diffuse_color = crgba(p)
    return m


def make_core_material(name, p, s, accent_mix, strength):
    """Bright marbled inner core; noise gives animated energy swirls."""
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Strength"].default_value = strength

    noise = nt.nodes.new("ShaderNodeTexNoise")
    try:
        noise.noise_dimensions = "4D"
    except Exception:
        pass
    noise.inputs["Scale"].default_value = 4.2
    noise.inputs["Detail"].default_value = 3.0
    noise.inputs["Roughness"].default_value = 0.62
    noise.inputs["W"].default_value = 0.0

    n_ramp = nt.nodes.new("ShaderNodeValToRGB")
    accent = cmix(p, s, accent_mix)
    ramp_set(n_ramp, [(0.00, cdark(p, 0.30)),
                      (0.42, cmix(p, accent, 0.45)),
                      (0.72, clight(p, 0.24)),
                      (1.00, clight(accent, 0.50))])

    # A little Fresnel so faceted cores (crystal / diamond) read as 3-D.
    lw = nt.nodes.new("ShaderNodeLayerWeight")
    lw.inputs["Blend"].default_value = 0.4
    f_ramp = nt.nodes.new("ShaderNodeValToRGB")
    ramp_set(f_ramp, [(0.0, cdark(p, 0.45)), (1.0, clight(accent, 0.40))])

    mix = nt.nodes.new("ShaderNodeMixRGB")
    mix.blend_type = "MIX"
    mix.inputs["Factor"].default_value = 0.32
    nt.links.new(n_ramp.outputs["Color"], mix.inputs["Color1"])
    nt.links.new(f_ramp.outputs["Color"], mix.inputs["Color2"])
    nt.links.new(lw.outputs["Fresnel"], f_ramp.inputs["Fac"])
    nt.links.new(noise.outputs["Fac"], n_ramp.inputs["Fac"])
    nt.links.new(mix.outputs["Color"], em.inputs["Color"])
    nt.links.new(em.outputs[0], out.inputs["Surface"])
    m.diffuse_color = crgba(p)
    return m, noise


def make_backdrop_material():
    """Very dark radial nebula; a mesh plane, so Generated coords are reliable."""
    m = bpy.data.materials.new("NebulaBackdrop")
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Strength"].default_value = 1.0
    tc = nt.nodes.new("ShaderNodeTexCoord")
    dist = nt.nodes.new("ShaderNodeVectorMath")
    dist.operation = "DISTANCE"
    dist.inputs[1].default_value = (0.5, 0.5, 0.0)
    ramp = nt.nodes.new("ShaderNodeValToRGB")
    ramp_set(ramp, [(0.00, (0.055, 0.020, 0.115)),
                    (0.28, (0.016, 0.009, 0.038)),
                    (0.60, (0.004, 0.003, 0.012)),
                    (1.00, (0.001, 0.001, 0.003))])
    nt.links.new(tc.outputs["Generated"], dist.inputs[0])
    nt.links.new(dist.outputs["Value"], ramp.inputs["Fac"])
    nt.links.new(ramp.outputs["Color"], em.inputs["Color"])
    nt.links.new(em.outputs[0], out.inputs["Surface"])
    return m


