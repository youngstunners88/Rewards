def render_animation_frames(scene, rig, out_dir, frames=None, res=ANIM_RES):
    os.makedirs(out_dir, exist_ok=True)
    scene.render.resolution_x = res
    scene.render.resolution_y = res
    scene.render.film_transparent = False
    scene.render.image_settings.color_mode = "RGB"
    scene.cycles.samples = ANIM_SAMPLES
    scene.render.use_persistent_data = True

    if frames is None:
        scene.render.filepath = os.path.join(out_dir, "frame_")
        log("Rendering %d animation frames at %dx%d / %d spp -> %s"
            % (N_FRAMES, res, res, ANIM_SAMPLES, out_dir))
        bpy.ops.render.render(animation=True)
    else:
        for f in frames:
            scene.frame_set(f)
            scene.render.filepath = os.path.join(out_dir, "f%04d.png" % f)
            bpy.ops.render.render(write_still=True)
        log("Preview frames rendered: %s" % frames)


def encode(frame_dir, out_webm, out_mp4):
    pattern = os.path.join(frame_dir, "frame_%04d.png")
    base = ["ffmpeg", "-hide_banner", "-loglevel", "warning", "-y",
            "-framerate", str(FPS), "-start_number", "1", "-i", pattern,
            "-frames:v", str(N_FRAMES), "-r", str(FPS), "-an"]

    log("Encoding VP9 webm ...")
    subprocess.run(base + [
        "-c:v", "libvpx-vp9", "-crf", "32", "-b:v", "0",
        "-deadline", "good", "-cpu-used", "4", "-row-mt", "1",
        "-threads", "4", "-pix_fmt", "yuv420p", out_webm], check=True)

    log("Encoding H.264 mp4 ...")
    subprocess.run(base + [
        "-c:v", "libx264", "-preset", "medium", "-crf", "26",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", out_mp4], check=True)


def ffprobe(path):
    out = subprocess.check_output([
        "ffprobe", "-v", "error",
        "-show_entries", "format=duration:stream=width,height,r_frame_rate,nb_frames",
        "-of", "default=noprint_wrappers=1", path], text=True)
    d = {}
    for line in out.strip().splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            d[k.strip()] = v.strip()
    return d


